-- Adds the MII Inspections table and the private "inspection-documents" storage bucket.

-- Carry over the table if the earlier version of this script (public.inspections) was run.
do $$
begin
  if to_regclass('public.inspections') is not null
     and to_regclass('public.mii_inspections') is null then
    alter table public.inspections rename to mii_inspections;
    alter table public.mii_inspections rename column documents to supporting_documents;
    update public.mii_inspections set created_at = submitted_at;
    alter table public.mii_inspections drop column submitted_at;
  end if;
end $$;

create table if not exists public.mii_inspections (
  id integer primary key generated by default as identity,
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  created_by integer references public.app_users (id) on delete set null,
  updated_by integer references public.app_users (id) on delete set null,
  -- Storage paths inside the inspection-documents bucket.
  supporting_documents text[] not null default '{}',
  -- Both reference an MII order details row: one for its job, one for its drawing.
  job integer references public.mii_order_details (id) on delete set null,
  drawing integer references public.mii_order_details (id) on delete set null
);

alter table public.mii_inspections
  add column if not exists updated_at timestamptz default now(),
  add column if not exists created_by integer references public.app_users (id) on delete set null,
  add column if not exists updated_by integer references public.app_users (id) on delete set null,
  add column if not exists job integer references public.mii_order_details (id) on delete set null,
  add column if not exists drawing integer references public.mii_order_details (id) on delete set null;

create index if not exists mii_inspections_job_idx on public.mii_inspections (job);
create index if not exists mii_inspections_drawing_idx on public.mii_inspections (drawing);

-- Stamps updated_at and the signed-in app user on every insert/update.
create or replace function public.mii_inspections_audit()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  actor integer;
begin
  select id into actor from public.app_users where auth_user_id = auth.uid() limit 1;
  if tg_op = 'INSERT' then
    new.created_at := coalesce(new.created_at, now());
    new.created_by := coalesce(new.created_by, actor);
  end if;
  new.updated_at := now();
  new.updated_by := coalesce(actor, new.updated_by);
  return new;
end $$;

drop trigger if exists mii_inspections_audit on public.mii_inspections;
create trigger mii_inspections_audit
  before insert or update on public.mii_inspections
  for each row execute function public.mii_inspections_audit();

alter table public.mii_inspections enable row level security;

drop policy if exists "authenticated full access" on public.mii_inspections;
create policy "authenticated full access" on public.mii_inspections
  for all to authenticated using (true) with check (true);

-- Private bucket for supporting documents (opened via short-lived signed URLs).
insert into storage.buckets (id, name, public)
values ('inspection-documents', 'inspection-documents', false)
on conflict (id) do nothing;

drop policy if exists "authenticated read inspection documents" on storage.objects;
create policy "authenticated read inspection documents" on storage.objects
  for select to authenticated using (bucket_id = 'inspection-documents');

drop policy if exists "authenticated write inspection documents" on storage.objects;
create policy "authenticated write inspection documents" on storage.objects
  for insert to authenticated with check (bucket_id = 'inspection-documents');

drop policy if exists "authenticated delete inspection documents" on storage.objects;
create policy "authenticated delete inspection documents" on storage.objects
  for delete to authenticated using (bucket_id = 'inspection-documents');
