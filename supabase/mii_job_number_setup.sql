create table if not exists public.mii_job_number (
  id integer primary key generated by default as identity,
  job_number text not null default '',
  po_number text not null default '',
  due_date date,
  number_of_items double precision not null default 0,
  completed_items double precision not null default 0,
  status text not null default 'Not Started'
    check (status in (
      'Not Started', 'In Progress', 'Completed', 'Shipped', 'Requires Attention', 'Mistake'
    )),
  -- Entered by hand: positive = days left, negative = days behind.
  days_left double precision,
  created_at timestamptz default now()
);

alter table public.mii_job_number enable row level security;

drop policy if exists "authenticated full access" on public.mii_job_number;
create policy "authenticated full access" on public.mii_job_number
  for all to authenticated using (true) with check (true);
