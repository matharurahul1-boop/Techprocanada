-- (Settings > SQL Editor > New query), after jobs_setup.sql.
-- Adds the MII Order Details table for the Job tab. Its drawing_number values
-- feed the Drawing Number dropdown on the Machining Hours page.

create table if not exists public.mii_order_details (
  id integer primary key generated by default as identity,
  job_id integer references public.jobs (id) on delete set null,
  drawing_number text not null default '',
  drawing_name text not null default '',
  quantity double precision not null default 0,
  quantity_completed double precision not null default 0,
  order_status text not null default 'Not Started'
    check (order_status in (
      'Not Started', 'In Progress', 'Completed', 'Shipped', 'Requires Attention', 'Mistake'
    )),
  completed boolean not null default false,
  completed_date date,
  inspected boolean not null default false,
  shipment boolean not null default false,
  shipment_date date,
  remarks text not null default '',
  -- Durations in whole minutes (shown as h:mm in the app). Variance is computed, not stored.
  quoted_minutes integer check (quoted_minutes >= 0),
  actual_minutes integer check (actual_minutes >= 0),
  created_at timestamptz default now()
);

alter table public.mii_order_details enable row level security;

drop policy if exists "authenticated full access" on public.mii_order_details;
create policy "authenticated full access" on public.mii_order_details
  for all to authenticated using (true) with check (true);
