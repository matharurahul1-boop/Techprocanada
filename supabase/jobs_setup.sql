-- Adds the Jobs table and the private "packing-slips" storage bucket.

create table if not exists public.jobs (
  id integer primary key generated by default as identity,
  company_id integer references public.companies (id) on delete set null,
  job_number text not null default '',
  job_date date,
  due_date date,
  number_of_items double precision not null default 0,
  completed_items double precision not null default 0,
  job text not null default '',
  status text not null default 'Not Started'
    check (status in (
      'Not Started', 'In Progress', 'Partially Completed', 'Completed',
      'Shipped', 'Requires Attention', 'Mistake'
    )),
  po_number text not null default '',
  ship_date date,
  packing_slips text[] not null default '{}',
  priority boolean not null default false,
  created_at timestamptz default now()
);

alter table public.jobs enable row level security;

drop policy if exists "authenticated full access" on public.jobs;
create policy "authenticated full access" on public.jobs
  for all to authenticated using (true) with check (true);

-- Private bucket for packing slip files (opened via short-lived signed URLs).
insert into storage.buckets (id, name, public)
values ('packing-slips', 'packing-slips', false)
on conflict (id) do nothing;

drop policy if exists "authenticated read packing slips" on storage.objects;
create policy "authenticated read packing slips" on storage.objects
  for select to authenticated using (bucket_id = 'packing-slips');

drop policy if exists "authenticated write packing slips" on storage.objects;
create policy "authenticated write packing slips" on storage.objects
  for insert to authenticated with check (bucket_id = 'packing-slips');

drop policy if exists "authenticated delete packing slips" on storage.objects;
create policy "authenticated delete packing slips" on storage.objects
  for delete to authenticated using (bucket_id = 'packing-slips');
