-- Adds the Quoted Hours table for the Job tab. Price (job_hours * rate) is
-- computed in the app, not stored.

create table if not exists public.quoted_hours (
  id integer primary key generated by default as identity,
  job_id integer references public.jobs (id) on delete set null,
  -- Picked from mii_order_details.drawing_number for the selected job.
  drawing_number text not null default '',
  quantity double precision not null default 0,
  machine_id integer references public.machines (id) on delete set null,
  job_hours double precision not null default 0,
  rate numeric(12, 2) not null default 0,
  description text not null default '',
  time_remaining text not null default '',
  created_at timestamptz default now()
);

alter table public.quoted_hours enable row level security;

drop policy if exists "authenticated full access" on public.quoted_hours;
create policy "authenticated full access" on public.quoted_hours
  for all to authenticated using (true) with check (true);
