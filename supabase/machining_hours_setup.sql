-- Adds the Machining Hours table for the Job tab. This is separate from the
-- older machine_hours table behind the hidden /machine-hours page.

create table if not exists public.machining_hours (
  id integer primary key generated by default as identity,
  work_date date,
  user_id integer references public.app_users (id) on delete set null,
  machine_id integer references public.machines (id) on delete set null,
  description text not null default '',
  job_id integer references public.jobs (id) on delete set null,
  -- Will be picked from mii_order_details.drawing_number once that table exists.
  drawing_number text not null default '',
  created_at timestamptz default now()
);

alter table public.machining_hours enable row level security;

drop policy if exists "authenticated full access" on public.machining_hours;
create policy "authenticated full access" on public.machining_hours
  for all to authenticated using (true) with check (true);
